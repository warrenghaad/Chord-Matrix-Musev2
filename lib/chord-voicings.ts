export interface ChordVoicing {
  name: string;
  frets: (number | -1)[];
  fingers: (number | 0)[];
  barFret?: number;
  barString?: [number, number];
  startFret: number;
}

type StringState = number | -1;

function v(
  frets: StringState[],
  fingers: (number | 0)[],
  startFret: number = 1,
  bar?: { fret: number; from: number; to: number }
): Omit<ChordVoicing, "name"> {
  return {
    frets,
    fingers,
    startFret,
    ...(bar ? { barFret: bar.fret, barString: [bar.from, bar.to] as [number, number] } : {}),
  };
}

